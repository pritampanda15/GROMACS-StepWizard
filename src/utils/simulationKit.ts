import JSZip from 'jszip';
import { MDP_PRESETS, MdpConfig, generateMdpText } from '../data/mdpPresets';

export interface KitExportOptions {
  productionConfig: MdpConfig;
  presetName: string;
  mdpFilename: string;
  slurmMaxh: number;
  estimatedNsPerDay: number;
}

const IONS_MDP = `; ions.mdp - used as input into grompp to generate ions.tpr
integrator  = steep
emtol       = 1000.0
emstep      = 0.01
nsteps      = 50000
nstlist     = 1
cutoff-scheme = Verlet
coulombtype = cutoff
rcoulomb    = 1.0
rvdw        = 1.0
pbc         = xyz
`;

export async function downloadSimulationKitZip(opts: KitExportOptions): Promise<string> {
  const { productionConfig, presetName, mdpFilename, slurmMaxh, estimatedNsPerDay } = opts;
  const zip = new JSZip();

  const emPreset = MDP_PRESETS.find((p) => p.id === 'energy-minimization')!;
  const nvtPreset = MDP_PRESETS.find((p) => p.id === 'nvt-equilibration')!;
  const nptPreset = MDP_PRESETS.find((p) => p.id === 'npt-equilibration')!;

  const isCharmm = presetName.toLowerCase().includes('charmm');
  const sharedCutoffs = isCharmm
    ? { rlist: 1.2, rcoulomb: 1.2, rvdw: 1.2, vdwModifier: 'Force-switch', rvdwSwitch: 1.0 }
    : { rcoulomb: productionConfig.rcoulomb, rvdw: productionConfig.rvdw };

  const minimMdp = generateMdpText({
    ...emPreset.config,
    ...sharedCutoffs,
    nsteps: 50000,
    timePs: 100,
  });

  const nvtMdp = generateMdpText({
    ...nvtPreset.config,
    ...sharedCutoffs,
    dt: productionConfig.dt,
    temperature: productionConfig.temperature,
    tcGrps: productionConfig.tcGrps,
    tauT: productionConfig.tauT,
    timePs: 100,
    nsteps: Math.round(100 / productionConfig.dt),
  });

  const nptMdp = generateMdpText({
    ...nptPreset.config,
    ...sharedCutoffs,
    dt: productionConfig.dt,
    temperature: productionConfig.temperature,
    pcoupltype: productionConfig.pcoupltype,
    tcGrps: productionConfig.tcGrps,
    tauT: productionConfig.tauT,
    compressibility: productionConfig.compressibility,
    timePs: 500,
    nsteps: Math.round(500 / productionConfig.dt),
  });

  const prodMdp = generateMdpText(productionConfig);

  const gpuFlags =
    productionConfig.constraints === 'h-bonds'
      ? `-nb gpu -pme gpu -bonded gpu -update gpu -nstlist ${Math.max(productionConfig.nstlist, 40)} -pin on`
      : `-nb gpu -pme gpu -bonded gpu -pin on`;

  const runLocalSh = `#!/usr/bin/env bash
# =============================================================================
# Local NVIDIA GPU GROMACS Pipeline — Generated by GROMACS StepWizard
# Protocol: ${presetName} | ${productionConfig.timePs / 1000} ns (${productionConfig.nsteps.toLocaleString()} steps @ dt=${productionConfig.dt} ps)
# =============================================================================
set -euo pipefail

GMX="\${GMX:-gmx}"
PDB="\${PDB:-protein.pdb}"
NTOMP="\${NTOMP:-8}"
export GMX_ENABLE_DIRECT_GPU_COMM=1
export GMX_CUDA_GRAPH=1

# 1. Topology, box, solvation & ions
"\${GMX}" pdb2gmx -f "\${PDB}" -o processed.gro -water ${isCharmm ? 'tip3p' : 'spce'} -ignh
"\${GMX}" editconf -f processed.gro -o newbox.gro -c -d 1.0 -bt dodecahedron
"\${GMX}" solvate -cp newbox.gro -cs spc216.gro -o solv.gro -p topol.top
"\${GMX}" grompp -f ions.mdp -c solv.gro -p topol.top -o ions.tpr -maxwarn 1
printf "SOL\\n" | "\${GMX}" genion -s ions.tpr -o solv_ions.gro -p topol.top -pname NA -nname CL -neutral -conc 0.15

# 2. Energy Minimization
"\${GMX}" grompp -f minim.mdp -c solv_ions.gro -p topol.top -o em.tpr
"\${GMX}" mdrun -v -deffnm em

# 3. NVT Equilibration (${productionConfig.temperature} K)
"\${GMX}" grompp -f nvt.mdp -c em.gro -r em.gro -p topol.top -o nvt.tpr
"\${GMX}" mdrun -v -deffnm nvt -ntmpi 1 -ntomp "\${NTOMP}" ${gpuFlags}

# 4. NPT Equilibration (C-rescale)
"\${GMX}" grompp -f npt.mdp -c nvt.gro -r nvt.gro -t nvt.cpt -p topol.top -o npt.tpr
"\${GMX}" mdrun -v -deffnm npt -ntmpi 1 -ntomp "\${NTOMP}" ${gpuFlags}

# 5. Production MD (${productionConfig.timePs / 1000} ns)
"\${GMX}" grompp -f ${mdpFilename} -c npt.gro -t npt.cpt -p topol.top -o md_0_1.tpr
"\${GMX}" mdrun -v -deffnm md_0_1 -ntmpi 1 -ntomp "\${NTOMP}" ${gpuFlags}

# 6. Post-processing: PBC centering & backbone RMSD
printf "1\\n0\\n" | "\${GMX}" trjconv -s md_0_1.tpr -f md_0_1.xtc -o md_0_1_center.xtc -center -pbc mol -ur compact
printf "4\\n4\\n" | "\${GMX}" rms -s md_0_1.tpr -f md_0_1_center.xtc -o rmsd.xvg -tu ns
`;

  const slurmSh = `#!/usr/bin/env bash
# =============================================================================
# SLURM NVIDIA GPU Job Script — Generated by GROMACS StepWizard
# =============================================================================
#SBATCH --job-name=gmx_prod
#SBATCH --time=24:00:00
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task=8
#SBATCH --gpus-per-node=1
#SBATCH --account=YOUR_ALLOCATION

set -euo pipefail
module load GROMACS/2024.2-CUDA

export OMP_NUM_THREADS=8
export GMX_ENABLE_DIRECT_GPU_COMM=1
export GMX_CUDA_GRAPH=1

# Compile TPR if not already present
if [ ! -f md_0_1.tpr ]; then
    gmx grompp -f ${mdpFilename} -c npt.gro -t npt.cpt -p topol.top -o md_0_1.tpr
fi

# Run with automatic checkpointing & graceful -maxh shutdown before walltime
gmx mdrun -v -deffnm md_0_1 \\
    -cpi md_0_1.cpt -append \\
    -ntmpi 1 -ntomp "\${OMP_NUM_THREADS}" \\
    ${gpuFlags} \\
    -maxh ${slurmMaxh.toFixed(1)}
`;

  const readmeTxt = `GROMACS StepWizard — Simulation Kit
========================================
Protocol:       ${presetName}
Duration:       ${productionConfig.timePs / 1000} ns (${productionConfig.timePs.toLocaleString()} ps)
Timestep (dt):  ${productionConfig.dt} ps (${productionConfig.dt * 1000} fs)
Total nsteps:   ${productionConfig.nsteps.toLocaleString()}
Temperature:    ${productionConfig.temperature} K
Thermostat:     ${productionConfig.tcoupl}
Barostat:       ${productionConfig.pcoupl} (${productionConfig.pcoupltype})
Est. Speed:     ~${estimatedNsPerDay.toFixed(0)} ns/day

Included Files:
  - ions.mdp             Neutralization & ionic strength setup
  - minim.mdp            Steepest-descent energy minimization
  - nvt.mdp              100 ps restrained NVT thermalization
  - npt.mdp              500 ps restrained NPT C-rescale equilibration
  - ${mdpFilename.padEnd(20)} Production run parameters (${productionConfig.nsteps.toLocaleString()} steps)
  - run_local_gpu.sh     End-to-end local NVIDIA GPU workflow
  - slurm_gpu_md.sh      HPC SLURM GPU job with -cpi -append -maxh ${slurmMaxh.toFixed(1)}

Quick Start:
  chmod +x run_local_gpu.sh slurm_gpu_md.sh
  ./run_local_gpu.sh   # or: sbatch slurm_gpu_md.sh
`;

  zip.file('ions.mdp', IONS_MDP);
  zip.file('minim.mdp', minimMdp);
  zip.file('nvt.mdp', nvtMdp);
  zip.file('npt.mdp', nptMdp);
  zip.file(mdpFilename, prodMdp);
  zip.file('run_local_gpu.sh', runLocalSh);
  zip.file('slurm_gpu_md.sh', slurmSh);
  zip.file('README_KIT.txt', readmeTxt);

  const blob = await zip.generateAsync({ type: 'blob' });
  const zipName = `gromacs_kit_${productionConfig.timePs / 1000}ns.zip`;
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = zipName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
  return zipName;
}
